<#
.SYNOPSIS
    Pester 5 tests for the name check in tools/LabCommon.psm1 (issue #438).

.DESCRIPTION
    Key vault, container registry and web app names are unique across Azure. On 2026-10-27 the
    defaults of Labs 3.2 and 3.3 were taken outside the test subscription, and both deploys failed
    minutes in with errors that do not say which parameter to change. These tests pin that:

      1. Get-LabNameUnavailableReason asks the right ARM endpoint for each kind and reads the answer.
      2. A request that fails, or an answer without nameAvailable, throws rather than reading as free.
      3. Test-LabGlobalName stops on a taken name and on a check that could not run, names the
         parameter, and does not ask about a name the lab already owns.
      4. The deploy scripts of Labs 3.2, 3.3 and 3.4 run the check with their own parameter (the storage
         account deploys of Labs 4.1-4.4 are held in tests/Storage-Account-Names.Tests.ps1).

    Nothing reaches Azure: Invoke-AzRestMethod is mocked inside the module.

.EXAMPLE
    Invoke-Pester -Path .\tests\LabCommon-GlobalName.Tests.ps1

.NOTES
    Project: SkyCraft
    Issue: #438
#>

#Requires -Version 7.0
#Requires -Modules @{ ModuleName = 'Pester'; ModuleVersion = '5.0.0' }

BeforeDiscovery {
    $root = Join-Path $PSScriptRoot '..'
    $script:DeployCases = @(
        @{ Lab = '3.2'; Path = (Join-Path $root 'module-3-compute/3.2-virtual-machines/scripts/Deploy-Bicep.ps1'); Kind = 'KeyVault'; Parameter = 'KeyVaultName' }
        @{ Lab = '3.3'; Path = (Join-Path $root 'module-3-compute/3.3-containers/scripts/Deploy-Bicep.ps1'); Kind = 'ContainerRegistry'; Parameter = 'AcrName' }
        @{ Lab = '3.4'; Path = (Join-Path $root 'module-3-compute/3.4-app-service/scripts/Deploy-Bicep.ps1'); Kind = 'WebApp'; Parameter = 'AppName' }
    )
}

BeforeAll {
    Import-Module (Join-Path $PSScriptRoot '..' 'tools' 'LabCommon.psm1') -Force

    function Get-ArmAnswer {
        param([int]$Status = 200, [string]$Content)
        [pscustomobject]@{ StatusCode = $Status; Content = $Content }
    }
}

Describe 'Get-LabNameUnavailableReason (#438)' {

    It 'returns $null for a free name' {
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Content '{"nameAvailable":true,"reason":"","message":""}' }
        Get-LabNameUnavailableReason -Kind KeyVault -Name 'dev-skycraft-swc-kv-ab' -SubscriptionId 'sub' | Should -BeNullOrEmpty
    }

    It 'returns Azure''s reason for a taken name' {
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Content '{"nameAvailable":false,"reason":"AlreadyExists","message":"The registry devskycraftswcacr01 is already in use."}' }
        Get-LabNameUnavailableReason -Kind ContainerRegistry -Name 'devskycraftswcacr01' -SubscriptionId 'sub' |
            Should -Be 'AlreadyExists: The registry devskycraftswcacr01 is already in use.'
    }

    It 'asks <Kind> at <Expected>' -ForEach @(
        @{ Kind = 'KeyVault';          Expected = '/subscriptions/sub/providers/Microsoft.KeyVault/checkNameAvailability?api-version=2023-07-01';          Type = 'Microsoft.KeyVault/vaults' }
        @{ Kind = 'ContainerRegistry'; Expected = '/subscriptions/sub/providers/Microsoft.ContainerRegistry/checkNameAvailability?api-version=2023-07-01'; Type = 'Microsoft.ContainerRegistry/registries' }
        @{ Kind = 'WebApp';            Expected = '/subscriptions/sub/providers/Microsoft.Web/locations/northeurope/checknameavailability?api-version=2024-04-01'; Type = 'Site' }
        @{ Kind = 'StorageAccount';    Expected = '/subscriptions/sub/providers/Microsoft.Storage/checkNameAvailability?api-version=2023-05-01'; Type = 'Microsoft.Storage/storageAccounts' }
    ) {
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Content '{"nameAvailable":true}' }
        Get-LabNameUnavailableReason -Kind $Kind -Name 'some-name' -Location 'northeurope' -SubscriptionId 'sub' | Out-Null
        Should -Invoke -ModuleName LabCommon Invoke-AzRestMethod -Times 1 -Exactly -ParameterFilter {
            $Method -eq 'POST' -and $Path -eq $Expected -and ($Payload | ConvertFrom-Json).type -eq $Type -and ($Payload | ConvertFrom-Json).name -eq 'some-name'
        }
    }

    It 'checks a web app with the TenantReuse scope the lab deploys it with' {
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Content '{"nameAvailable":true}' }
        Get-LabNameUnavailableReason -Kind WebApp -Name 'dev-skycraft-swc-app01' -SubscriptionId 'sub' | Out-Null
        Should -Invoke -ModuleName LabCommon Invoke-AzRestMethod -Times 1 -Exactly -ParameterFilter {
            ($Payload | ConvertFrom-Json).autoGeneratedDomainNameLabelScope -eq 'TenantReuse'
        }
    }

    It 'throws when ARM refuses the request' {
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Status 403 -Content '{"error":{"code":"AuthorizationFailed","message":"no"}}' }
        { Get-LabNameUnavailableReason -Kind KeyVault -Name 'x-kv' -SubscriptionId 'sub' } | Should -Throw '*AuthorizationFailed*'
    }

    It 'throws when the answer has no nameAvailable' {
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Content '{}' }
        { Get-LabNameUnavailableReason -Kind KeyVault -Name 'x-kv' -SubscriptionId 'sub' } | Should -Throw '*without nameAvailable*'
    }
}

Describe 'Test-LabGlobalName (#438)' {

    It 'does not ask about a name the lab already owns' {
        Mock -ModuleName LabCommon Invoke-AzRestMethod { throw 'must not be called' }
        Test-LabGlobalName -Kind KeyVault -Name 'dev-skycraft-swc-kv' -ParameterName KeyVaultName -Owned $true 6>$null | Should -BeTrue
        Should -Invoke -ModuleName LabCommon Invoke-AzRestMethod -Times 0 -Exactly
    }

    It 'lets the deploy go on when the name is free' {
        Mock -ModuleName LabCommon Get-AzContext { [pscustomobject]@{ Subscription = [pscustomobject]@{ Id = 'sub' } } }
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Content '{"nameAvailable":true}' }
        Test-LabGlobalName -Kind ContainerRegistry -Name 'devskycraftswcacr01ab' -ParameterName AcrName -Owned $false 6>$null | Should -BeTrue
    }

    It 'stops on a taken name and names the parameter to change' {
        Mock -ModuleName LabCommon Get-AzContext { [pscustomobject]@{ Subscription = [pscustomobject]@{ Id = 'sub' } } }
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Content '{"nameAvailable":false,"reason":"AlreadyExists","message":"taken"}' }
        $lines = @(Test-LabGlobalName -Kind ContainerRegistry -Name 'devskycraftswcacr01' -ParameterName AcrName -Owned $false 6>&1)
        $lines[-1] | Should -BeFalse
        ($lines | Out-String) | Should -Match "\[ERROR\] The container registry name 'devskycraftswcacr01' is taken"
        ($lines | Out-String) | Should -Match '-AcrName'
    }

    It 'stops on a taken storage account name and names the parameter to change (#438)' {
        Mock -ModuleName LabCommon Get-AzContext { [pscustomobject]@{ Subscription = [pscustomobject]@{ Id = 'sub' } } }
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Content '{"nameAvailable":false,"reason":"AlreadyExists","message":"The storage account named prodskycraftswcsa is already taken."}' }
        $lines = @(Test-LabGlobalName -Kind StorageAccount -Name 'prodskycraftswcsa' -ParameterName ProdSaName -Owned $false 6>&1)
        $lines[-1] | Should -BeFalse
        ($lines | Out-String) | Should -Match "\[ERROR\] The storage account name 'prodskycraftswcsa' is taken \(AlreadyExists"
        ($lines | Out-String) | Should -Match '-ProdSaName'
        ($lines | Out-String) | Should -Match '3-24 lowercase letters and digits'
    }

    It 'lets a free storage account name through' {
        Mock -ModuleName LabCommon Get-AzContext { [pscustomobject]@{ Subscription = [pscustomobject]@{ Id = 'sub' } } }
        Mock -ModuleName LabCommon Invoke-AzRestMethod { Get-ArmAnswer -Content '{"nameAvailable":true}' }
        Test-LabGlobalName -Kind StorageAccount -Name 'prodskycraftswcsaab' -ParameterName ProdSaName -Owned $false 6>$null | Should -BeTrue
    }

    It 'stops when the check cannot run, rather than reading it as free' {
        Mock -ModuleName LabCommon Get-AzContext { [pscustomobject]@{ Subscription = [pscustomobject]@{ Id = 'sub' } } }
        Mock -ModuleName LabCommon Invoke-AzRestMethod { throw 'network down' }
        $lines = @(Test-LabGlobalName -Kind WebApp -Name 'dev-skycraft-swc-app01' -ParameterName AppName -Owned $false 6>&1)
        $lines[-1] | Should -BeFalse
        ($lines | Out-String) | Should -Match '\[ERROR\] Could not check'
    }
}

Describe 'Deploy-Bicep.ps1 of Labs 3.2-3.4 checks its name before deploying (#438)' {

    It 'Lab <Lab> calls Test-LabGlobalName -Kind <Kind> with -ParameterName <Parameter>' -ForEach $script:DeployCases {
        $ast = [System.Management.Automation.Language.Parser]::ParseFile($Path, [ref]$null, [ref]$null)
        $calls = @($ast.FindAll({
                    param($node)
                    $node -is [System.Management.Automation.Language.CommandAst] -and $node.GetCommandName() -eq 'Test-LabGlobalName'
                }, $true))
        $calls.Count | Should -Be 1
        $text = $calls[0].Extent.Text
        $text | Should -Match "-Kind $Kind\b"
        $text | Should -Match "-ParameterName '$Parameter'"
        @($ast.ParamBlock.Parameters | ForEach-Object { $_.Name.VariablePath.UserPath }) | Should -Contain $Parameter
    }

    It 'Lab <Lab> stops with Exit-Lab when the check fails' -ForEach $script:DeployCases {
        $source = Get-Content -Raw -LiteralPath $Path
        $source | Should -Match '(?s)if \(-not \(Test-LabGlobalName [^\r\n]+\)\) \{\s+Exit-Lab -FailureCount 1'
    }
}
